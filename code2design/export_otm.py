"""Open Threat Model (OTM 0.2.0) export.

boundaries -> trustZones; processes, entities, stores -> components (one parent each); flows ->
dataflows; assets -> assets; controls -> mitigations; weaknesses -> threats (STRIDE categories,
CWE, impact from severity, likelihood left for the team) attached to the components they apply to.
Evidence becomes a `code` representation (file and line) where OTM allows one, and an attribute
elsewhere."""
from collections import OrderedDict
from .model import WEAKNESSES

ZONE_TYPE = {"internet": "public-cloud"}
STRIDE_NAMES = {"S": "Spoofing", "T": "Tampering", "R": "Repudiation", "I": "Information Disclosure", "D": "Denial of Service", "E": "Elevation of Privilege"}
IMPACT = {"high": 80, "medium": 50, "low": 20, "info": 5}
CONFIDENTIALITY = {"secret": 100, "credential": 100, "health": 90, "pii": 80, "financial": 80, "internal": 40, "public": 10, "unknown": 50}
MITIGATION_REDUCTION = {"authn": 60, "authz": 60, "input_validation": 40, "csrf": 40, "rate_limit": 20, "tls": 50, "encryption_at_rest": 50, "signing": 50, "audit_log": 20, "cors": 20, "security_headers": 20}


def _evidence_attr(n):
    e = n["evidence"][0] if n.get("evidence") else None
    return f"{e['path']}:{e['start_line']}" if e else None


def to_otm(ir, repo_url=None):
    name = ir["provenance"]["generated_from"]
    rep = "code"
    otm = OrderedDict(otmVersion="0.2.0", project=OrderedDict(name=name, id=f"code2design-{name}",
                                                             description=f"Generated by code2design {ir['provenance']['tool_version']} from commit {ir['provenance']['commit'][:12]}"))
    otm["representations"] = [OrderedDict(name="Source code", id=rep, type="code", repository=OrderedDict(url=repo_url or name))]

    def code_rep(n):
        e = n["evidence"][0] if n.get("evidence") else None
        return [OrderedDict(representation=rep, id=f"{n['id']}-code", file=e["path"], line=e["start_line"])] if e else []
    zones, bnd_of = [], {}
    for b in sorted(ir["boundaries"], key=lambda b: (-len(b["contains"]), b["id"])):
        zones.append(OrderedDict(id=b["id"], name=b["name"], type=ZONE_TYPE.get(b["kind"], "private-secured"), risk=OrderedDict(trustRating=10 if b["kind"] == "internet" else 80),
                                 representations=code_rep(b), attributes=OrderedDict(kind=b["kind"], origin=b["origin"])))
        for x in b["contains"]:
            bnd_of.setdefault(x, b["id"])
    zones.append(OrderedDict(id="tz-internet", name="Internet", type="public-cloud", risk=OrderedDict(trustRating=1)))
    otm["trustZones"] = sorted(zones, key=lambda z: z["id"])
    threats_on = {}
    proc_of_ep = {e["id"]: e["process"] for e in ir["entry_points"]}
    for w in ir["weaknesses"]:
        for x in w["applies_to"]:
            threats_on.setdefault(proc_of_ep.get(x, x), []).append(w["id"])

    def threats(nid):
        return [OrderedDict(threat=t, state="exposed", mitigations=[]) for t in sorted(set(threats_on.get(nid, [])))]
    comps = []
    for p in ir["processes"]:
        parent = OrderedDict(component=p["parent"]) if p.get("parent") else OrderedDict(trustZone=bnd_of.get(p["id"], "tz-internet"))
        if p.get("parent") and p["id"] in bnd_of and bnd_of.get(p["parent"]) != bnd_of[p["id"]]:
            parent = OrderedDict(trustZone=bnd_of[p["id"]])
        comps.append(OrderedDict(id=p["id"], name=p["name"], type="process" if p["level"] == 2 else "service", parent=parent, representations=code_rep(p), threats=threats(p["id"]),
                                 tags=[f"level:{p['level']}", f"origin:{p['origin']}"], attributes=OrderedDict(module=p["module"])))
    for e in ir["entities"]:
        comps.append(OrderedDict(id=e["id"], name=e["name"], type="llm" if e["kind"] == "llm_api" else "external-entity", parent=OrderedDict(trustZone=bnd_of.get(e["id"], "tz-internet")),
                                 representations=code_rep(e), threats=threats(e["id"]), tags=[f"kind:{e['kind']}", f"direction:{e['identity'][-1]}"],
                                 attributes=OrderedDict([("host", e["host"])] if e.get("host") else [])))
    stored = {}
    processed = {}
    for a in ir["assets"]:
        for s in a["held_by"]:
            stored.setdefault(s, []).append(a["id"])
        for s in a["processed_by"]:
            processed.setdefault(s, []).append(a["id"])
    for c in comps:
        if processed.get(c["id"]):
            c["assets"] = OrderedDict(processed=sorted(processed[c["id"]]), stored=[])
    for s in ir["stores"]:
        attrs = OrderedDict(technology=s["technology"], encryption_at_rest=s["encryption_at_rest"], data_classes=", ".join(s["data_classes"]))
        if s.get("candidate_engines"):
            attrs["candidate_engines"] = ", ".join(s["candidate_engines"])
        comps.append(OrderedDict(id=s["id"], name=s["name"], type="datastore", parent=OrderedDict(trustZone=bnd_of.get(s["id"], "tz-internet")),
                                 assets=OrderedDict(processed=sorted(processed.get(s["id"], [])), stored=sorted(stored.get(s["id"], []))),
                                 representations=code_rep(s), threats=threats(s["id"]), tags=[f"technology:{s['technology']}"] + [f"data:{c}" for c in s["data_classes"]], attributes=attrs))
    otm["components"] = comps
    ctl = {c["id"]: c for c in ir["controls"]}
    assets_by_class = {}
    for a in ir["assets"]:
        for c in a["data_classes"]:
            assets_by_class.setdefault(c, []).append(a["id"])
    flows = []
    for f in ir["flows"]:
        dcs = (f.get("payload") or {}).get("data_classes", [])
        flows.append(OrderedDict(id=f["id"], name=f.get("purpose") or f["protocol"], source=f["source"], destination=f["target"], bidirectional=f["direction"] == "request_response",
                                 assets=sorted({a for c in dcs for a in assets_by_class.get(c, [])}),
                                 tags=[f"protocol:{f['protocol']}", f"origin:{f['origin']}"] + [f"data:{c}" for c in dcs],
                                 attributes=OrderedDict(authentication=f["authentication"], encryption=f["encryption"], controls=", ".join(ctl[c]["name"] for c in f["controls"] if c in ctl),
                                                        evidence=_evidence_attr(f))))
    otm["dataflows"] = flows
    otm["assets"] = [OrderedDict(id=a["id"], name=a["name"], description=f"{a['kind']} asset ({a['origin']})",
                                 risk=OrderedDict(confidentiality=max(CONFIDENTIALITY.get(c, 50) for c in a["data_classes"]), integrity=70, availability=50),
                                 representations=code_rep(a), attributes=OrderedDict(kind=a["kind"], data_classes=", ".join(a["data_classes"]))) for a in ir["assets"]]
    otm["threats"] = [OrderedDict(id=w["id"], name=w["name"], description=WEAKNESSES[w["kind"]][3], categories=[STRIDE_NAMES[x] for x in w["stride"]], cwes=[w["cwe"]],
                                  risk=OrderedDict(likelihood=None, likelihoodComment="not rated: likelihood is a team judgement", impact=IMPACT.get(w["severity"], 20), impactComment=f"severity {w['severity']} from the weakness kind"),
                                  tags=[f"kind:{w['kind']}"], attributes=OrderedDict(evidence=_evidence_attr(w))) for w in ir["weaknesses"]]
    otm["mitigations"] = [OrderedDict(id=c["id"], name=c["name"], description=f"{c['kind']} control, scope {c['scope']}" + (" (conditionally registered)" if c.get("conditional") else ""),
                                      riskReduction=MITIGATION_REDUCTION.get(c["kind"], 20), attributes=OrderedDict(kind=c["kind"], evidence=_evidence_attr(c))) for c in ir["controls"]]
    return otm
