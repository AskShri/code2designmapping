"""Open Threat Model (OTM 0.2.0) export. Boundaries -> trustZones, processes/entities/stores ->
components (one parent each), flows -> dataflows, assets -> assets, evidence -> a `code`
representation with file and line per element."""
from collections import OrderedDict


def to_otm(ir, repo_url=None):
    name = ir["provenance"]["generated_from"]
    rep_id = "code"
    otm = OrderedDict(otmVersion="0.2.0", project=OrderedDict(name=name, id=f"code2design-{name}", description=f"Generated by code2design {ir['provenance']['tool_version']} from commit {ir['provenance']['commit'][:12]}"))
    otm["representations"] = [OrderedDict(name="Source code", id=rep_id, type="code", repository=OrderedDict(url=repo_url or name))]
    zones = []
    bnd_of = {}
    for b in ir["boundaries"]:
        zones.append(OrderedDict(id=b["id"], name=b["name"], type={"container": "private-secured", "repository": "private-secured", "internet": "public-cloud", "network_segment": "private-secured", "host": "private-secured", "process": "private-secured", "iam_role": "private-secured", "auth_context": "private-secured"}.get(b["kind"], "private-secured"), risk=OrderedDict(trustRating=10 if b["kind"] == "internet" else 80)))
        for x in b["contains"]:
            bnd_of.setdefault(x, b["id"])
    zones.append(OrderedDict(id="tz-internet", name="Internet", type="public-cloud", risk=OrderedDict(trustRating=1)))
    otm["trustZones"] = zones
    comps = []
    ctype = {"proc": "process", "ext": "external-entity", "store": "datastore"}

    def code_rep(n):
        e = n["evidence"][0] if n.get("evidence") else None
        return [OrderedDict(representation=rep_id, id=f"{n['id']}-code", file=e["path"], line=e["start_line"])] if e else []
    procs = {p["id"]: p for p in ir["processes"]}
    for p in ir["processes"]:
        parent = OrderedDict(component=p["parent"]) if p.get("parent") else OrderedDict(trustZone=bnd_of.get(p["id"], "tz-internet"))
        if p.get("parent") and p["id"] in bnd_of and bnd_of.get(p["parent"]) != bnd_of[p["id"]]:
            parent = OrderedDict(trustZone=bnd_of[p["id"]])
        comps.append(OrderedDict(id=p["id"], name=p.get("display_name") or p["name"], type="process" if p["level"] == 2 else "service", parent=parent, tags=[f"level:{p['level']}", f"module:{p['module']}"], representations=code_rep(p)))
    for e in ir["entities"]:
        comps.append(OrderedDict(id=e["id"], name=e["name"], type="external-entity" if e["kind"] != "llm_api" else "llm", parent=OrderedDict(trustZone=bnd_of.get(e["id"], "tz-internet")), tags=[f"kind:{e['kind']}"] + ([f"host:{e['host']}"] if e.get("host") else []), representations=code_rep(e)))
    assets_of = {}
    for a in ir["assets"]:
        for s in a["held_by"]:
            assets_of.setdefault(s, []).append(a["id"])
    for s in ir["stores"]:
        comps.append(OrderedDict(id=s["id"], name=s["name"], type="datastore", parent=OrderedDict(trustZone=bnd_of.get(s["id"], "tz-internet")), tags=[f"technology:{s['technology']}", f"encryption_at_rest:{s['encryption_at_rest']}"] + [f"data:{c}" for c in s["data_classes"]], assets=OrderedDict(processed=[], stored=assets_of.get(s["id"], [])), representations=code_rep(s)))
    otm["components"] = comps
    flows = []
    for f in ir["flows"]:
        tags = [f"protocol:{f['protocol']}", f"authentication:{f['authentication']}", f"encryption:{f['encryption']}"] + [f"data:{c}" for c in (f.get("payload") or {}).get("data_classes", [])] + [f"control:{c}" for c in f["controls"]]
        flows.append(OrderedDict(id=f["id"], name=f.get("purpose") or f["protocol"], source=f["source"], destination=f["target"], bidirectional=f["direction"] == "request_response", tags=tags, representations=code_rep(f)))
    otm["dataflows"] = flows
    rating = {"secret": 100, "credential": 100, "pii": 80, "financial": 80, "health": 90, "internal": 40, "public": 10, "unknown": 50}
    otm["assets"] = [OrderedDict(id=a["id"], name=a["name"], risk=OrderedDict(confidentiality=max(rating.get(c, 50) for c in a["data_classes"]), integrity=70, availability=50), tags=[f"kind:{a['kind']}", f"origin:{a['origin']}"], representations=code_rep(a)) for a in ir["assets"]]
    otm["threats"] = []
    otm["mitigations"] = [OrderedDict(id=c["id"], name=c["name"], riskReduction=50, tags=[f"kind:{c['kind']}"]) for c in ir["controls"]]
    return otm
